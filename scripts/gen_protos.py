"""Generate Python protobuf modules from proto/ into the integration package.

Usage (from the repo root, with the dev venv):
    .venv/bin/python scripts/gen_protos.py

protoc emits absolute imports (``from nest.trait import hvac_pb2``), which only
resolve when the output directory is on sys.path. Inside a Home Assistant
custom component it isn't, so imports of modules we generated are rewritten to
relative ones. Imports of anything we did *not* generate (``google.protobuf``,
and ``google.rpc.status_pb2`` from googleapis-common-protos) stay absolute.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "proto"
OUT_DIR = ROOT / "custom_components" / "protonest" / "pynestproto" / "proto_gen"

# Provided at runtime by googleapis-common-protos, which Home Assistant ships.
# Generating our own copy would register the same file in protobuf's global
# descriptor pool a second time.
SKIP = {"google/rpc/status.proto"}

INIT_DOC = '"""Generated by scripts/gen_protos.py from proto/. Do not edit."""\n'

# protoc output: "from a.b import c_pb2 as x" and, for root-level files,
# "import c_pb2 as x".
FROM_RE = re.compile(r"^from ([\w.]+) import (\w+)", re.MULTILINE)
IMPORT_RE = re.compile(r"^import (\w+_pb2)\b", re.MULTILINE)
# mypy-protobuf stubs: "import a.b.c_pb2".
DOTTED_IMPORT_RE = re.compile(r"^import ((?:\w+\.)+\w+_pb2)$", re.MULTILINE)

# Generated code refuses to load if the protobuf runtime differs from the
# gencode version. Home Assistant upgrades protobuf on its own schedule, and the
# wire format is stable across versions, so drop the check rather than let an
# HA update break the integration at import time.
RUNTIME_IMPORT_RE = re.compile(
    r"^from google\.protobuf import runtime_version as _runtime_version\n", re.MULTILINE
)
RUNTIME_CHECK_RE = re.compile(
    r"^_runtime_version\.ValidateProtobufRuntimeVersion\([^)]*\)\n",
    re.MULTILINE | re.DOTALL,
)


def run_protoc(sources: list[Path]) -> None:
    cmd = [
        sys.executable,
        "-m",
        "grpc_tools.protoc",
        f"-I{PROTO_DIR}",
        # Installed next to the interpreter; not on PATH unless the venv is activated.
        f"--plugin=protoc-gen-mypy={Path(sys.executable).parent / 'protoc-gen-mypy'}",
        f"--python_out={OUT_DIR}",
        f"--mypy_out={OUT_DIR}",
        *(str(p) for p in sources),
    ]
    subprocess.run(cmd, check=True)


def make_packages() -> None:
    for d in [OUT_DIR, *(p for p in OUT_DIR.rglob("*") if p.is_dir())]:
        (d / "__init__.py").write_text(INIT_DOC)


def generated_roots() -> set[str]:
    """Top-level names we generated, excluding the shared ``google`` namespace."""
    roots = {p.name for p in OUT_DIR.iterdir() if p.is_dir() and p.name != "google"}
    roots |= {p.stem for p in OUT_DIR.glob("*_pb2.py")}
    return roots


def is_ours(module: str, roots: set[str]) -> bool:
    if module.split(".")[0] in roots:
        return True
    # Within google/, only what we generated ourselves (e.g. stream_body).
    return module.startswith("google.") and (
        OUT_DIR / (module.replace(".", "/") + ".py")
    ).exists()


def fix_stub_dotted_imports(text: str, dots: str, roots: set[str]) -> str:
    """Rewrite ``import a.b.c_pb2`` in .pyi stubs, which mypy-protobuf emits.

    Stubs refer to the module by its full dotted name (``a.b.c_pb2.Msg``), so
    import it relatively under an alias and point those references at it.
    """
    for module in set(DOTTED_IMPORT_RE.findall(text)):
        if not is_ours(module, roots):
            continue
        pkg, name = module.rsplit(".", 1)
        alias = module.replace(".", "__")
        text = re.sub(
            rf"^import {re.escape(module)}$",
            f"from {dots}{pkg} import {name} as {alias}",
            text,
            flags=re.MULTILINE,
        )
        text = re.sub(rf"(?<![\w.]){re.escape(module)}(?=\.)", alias, text)
    return text


def fix_file(path: Path, roots: set[str]) -> None:
    depth = len(path.parent.relative_to(OUT_DIR).parts)
    dots = "." * (depth + 1)
    text = path.read_text()

    def from_sub(m: re.Match[str]) -> str:
        pkg, name = m.group(1), m.group(2)
        if is_ours(f"{pkg}.{name}", roots) or is_ours(pkg, roots):
            return f"from {dots}{pkg} import {name}"
        return m.group(0)

    def import_sub(m: re.Match[str]) -> str:
        mod = m.group(1)
        return f"from {dots} import {mod}" if mod in roots else m.group(0)

    new = FROM_RE.sub(from_sub, text)
    new = IMPORT_RE.sub(import_sub, new)
    if path.suffix == ".pyi":
        new = fix_stub_dotted_imports(new, dots, roots)
    if path.suffix == ".py":
        new = RUNTIME_IMPORT_RE.sub("", new)
        new = RUNTIME_CHECK_RE.sub("", new)
    if new != text:
        path.write_text(new)


def main() -> None:
    sources = sorted(
        p for p in PROTO_DIR.rglob("*.proto")
        if p.relative_to(PROTO_DIR).as_posix() not in SKIP
    )
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    run_protoc(sources)
    make_packages()
    roots = generated_roots()
    for path in OUT_DIR.rglob("*"):
        if path.suffix in (".py", ".pyi") and path.name != "__init__.py":
            fix_file(path, roots)

    count = len(list(OUT_DIR.rglob("*_pb2.py")))
    print(f"Generated {count} modules from {len(sources)} protos into {OUT_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
